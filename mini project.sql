-- PlantHub - Nursery Management System

DROP DATABASE IF EXISTS planthub;
CREATE DATABASE planthub;
USE planthub;

--  1. DDL - TABLES

CREATE TABLE Plant_Type (
    type_id    INT AUTO_INCREMENT PRIMARY KEY,
    type_name  VARCHAR(20) NOT NULL UNIQUE
);

CREATE TABLE Nursery (
    nursery_id    INT AUTO_INCREMENT PRIMARY KEY,
    name          VARCHAR(60) NOT NULL,
    state         VARCHAR(40) NOT NULL,
    city          VARCHAR(40) NOT NULL,
    pincode       CHAR(6)     NOT NULL,
    street        VARCHAR(80) NOT NULL
);

CREATE TABLE Supplier (
    supplier_id        INT AUTO_INCREMENT PRIMARY KEY,
    name               VARCHAR(60)  NOT NULL,
    contact_no         VARCHAR(15)  NOT NULL,
    address            VARCHAR(100) NOT NULL,
    country_of_origin  VARCHAR(40)  NOT NULL,
    mode_of_transport  VARCHAR(20) NOT NULL
);

CREATE TABLE Supplier_Plant_Type (
    supplier_id  INT NOT NULL,
    type_id      INT NOT NULL,
    PRIMARY KEY (supplier_id, type_id),
    FOREIGN KEY (supplier_id) REFERENCES Supplier(supplier_id) ON DELETE CASCADE,
    FOREIGN KEY (type_id)     REFERENCES Plant_Type(type_id)   ON DELETE CASCADE
);

CREATE TABLE Supplier_Nursery (
    supplier_id  INT NOT NULL,
    nursery_id   INT NOT NULL,
    PRIMARY KEY (supplier_id, nursery_id),
    FOREIGN KEY (supplier_id) REFERENCES Supplier(supplier_id) ON DELETE CASCADE,
    FOREIGN KEY (nursery_id)  REFERENCES Nursery(nursery_id)   ON DELETE CASCADE
);

CREATE TABLE Customer (
    customer_id    INT AUTO_INCREMENT PRIMARY KEY,
    name           VARCHAR(60)  NOT NULL,
    contact_no     CHAR(10)     NOT NULL UNIQUE,
    address        VARCHAR(100) NOT NULL,
    date_of_birth  DATE         NOT NULL
);

CREATE TABLE Staff (
    staff_id          INT AUTO_INCREMENT PRIMARY KEY,
    nursery_id        INT          NOT NULL,
    name              VARCHAR(60)  NOT NULL,
    contact_no        CHAR(10)     NOT NULL UNIQUE,
    date_of_birth     DATE         NOT NULL,
    experience_years  INT          NOT NULL DEFAULT 0,
    position          VARCHAR(30) NOT NULL,
    FOREIGN KEY (nursery_id) REFERENCES Nursery(nursery_id)
);

CREATE TABLE Plant (
    plant_id         INT AUTO_INCREMENT PRIMARY KEY,
    type_id          INT          NOT NULL,
    name             VARCHAR(50)  NOT NULL,
    botanical_name   VARCHAR(80)  NOT NULL,
    gender           VARCHAR(20) NOT NULL,
    season_of_plant  VARCHAR(20) NOT NULL,
    FOREIGN KEY (type_id) REFERENCES Plant_Type(type_id),
    UNIQUE (name, botanical_name, gender)
);

CREATE TABLE Nursery_Stock (
    nursery_id     INT           NOT NULL,
    plant_id       INT           NOT NULL,
    stock_qty      INT           NOT NULL DEFAULT 0,
    unit_price     DECIMAL(10,2) NOT NULL,
    reorder_level  INT           NOT NULL DEFAULT 20,
    PRIMARY KEY (nursery_id, plant_id),
    FOREIGN KEY (nursery_id) REFERENCES Nursery(nursery_id),
    FOREIGN KEY (plant_id)   REFERENCES Plant(plant_id)
);

CREATE TABLE Restock (
    restock_id    INT AUTO_INCREMENT PRIMARY KEY,
    supplier_id   INT           NOT NULL,
    nursery_id    INT           NOT NULL,
    plant_id      INT           NOT NULL,
    restock_date  DATE          NOT NULL,
    quantity      INT           NOT NULL,
    cost_price    DECIMAL(10,2) NOT NULL,          -- cost per plant paid to the supplier
    FOREIGN KEY (supplier_id, nursery_id) REFERENCES Supplier_Nursery(supplier_id, nursery_id),
    FOREIGN KEY (nursery_id, plant_id)    REFERENCES Nursery_Stock(nursery_id, plant_id)
);

CREATE TABLE Orders (
    order_id      INT AUTO_INCREMENT PRIMARY KEY,
    customer_id   INT  NOT NULL,
    nursery_id    INT  NOT NULL,
    order_date    DATE NOT NULL,
    payment_mode  VARCHAR(20) NOT NULL,
    FOREIGN KEY (customer_id) REFERENCES Customer(customer_id),
    FOREIGN KEY (nursery_id)  REFERENCES Nursery(nursery_id)
);

CREATE TABLE Order_Items (
    order_id    INT           NOT NULL,
    plant_id    INT           NOT NULL,
    quantity    INT           NOT NULL,
    unit_price  DECIMAL(10,2) NOT NULL,
    PRIMARY KEY (order_id, plant_id),
    FOREIGN KEY (order_id) REFERENCES Orders(order_id),
    FOREIGN KEY (plant_id) REFERENCES Plant(plant_id)
);

--  2. TRIGGERS (created before the data to update stock automatically)
DELIMITER $$

CREATE TRIGGER trg_oi_before_insert
BEFORE INSERT ON Order_Items
FOR EACH ROW
BEGIN
    IF NOT EXISTS (SELECT 1 FROM Orders WHERE order_id = NEW.order_id) THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Order does not exist';
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM Nursery_Stock ns
        JOIN Orders o ON o.nursery_id = ns.nursery_id
        WHERE o.order_id = NEW.order_id AND ns.plant_id = NEW.plant_id
    ) THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'This plant is not stocked at the order''s nursery';
    END IF;

    IF (SELECT ns.stock_qty
        FROM Nursery_Stock ns
        JOIN Orders o ON o.nursery_id = ns.nursery_id
        WHERE o.order_id = NEW.order_id AND ns.plant_id = NEW.plant_id) < NEW.quantity THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Insufficient stock for this plant';
    END IF;
END$$

CREATE TRIGGER trg_oi_after_insert
AFTER INSERT ON Order_Items
FOR EACH ROW
BEGIN
    UPDATE Nursery_Stock
    SET stock_qty = stock_qty - NEW.quantity
    WHERE nursery_id = (SELECT nursery_id FROM Orders WHERE order_id = NEW.order_id)
      AND plant_id = NEW.plant_id;
END$$

CREATE TRIGGER trg_oi_before_update
BEFORE UPDATE ON Order_Items
FOR EACH ROW
BEGIN
    IF NEW.order_id <> OLD.order_id OR NEW.plant_id <> OLD.plant_id THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Order or plant of an item cannot be changed; delete the item and add a new one';
    END IF;

    IF NEW.quantity > OLD.quantity AND
       (SELECT stock_qty
        FROM Nursery_Stock
        WHERE nursery_id = (SELECT nursery_id FROM Orders WHERE order_id = NEW.order_id)
          AND plant_id = NEW.plant_id) < NEW.quantity - OLD.quantity THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Insufficient stock for this plant';
    END IF;
END$$

CREATE TRIGGER trg_oi_after_update
AFTER UPDATE ON Order_Items
FOR EACH ROW
BEGIN
    IF NEW.quantity <> OLD.quantity THEN
        UPDATE Nursery_Stock
        SET stock_qty = stock_qty - (NEW.quantity - OLD.quantity)
        WHERE nursery_id = (SELECT nursery_id FROM Orders WHERE order_id = NEW.order_id)
          AND plant_id = NEW.plant_id;
    END IF;
END$$

CREATE TRIGGER trg_oi_after_delete
AFTER DELETE ON Order_Items
FOR EACH ROW
BEGIN
    UPDATE Nursery_Stock
    SET stock_qty = stock_qty + OLD.quantity
    WHERE nursery_id = (SELECT nursery_id FROM Orders WHERE order_id = OLD.order_id)
      AND plant_id = OLD.plant_id;
END$$

CREATE TRIGGER trg_orders_before_update
BEFORE UPDATE ON Orders
FOR EACH ROW
BEGIN
    IF NEW.nursery_id <> OLD.nursery_id
       AND EXISTS (SELECT 1 FROM Order_Items WHERE order_id = OLD.order_id) THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Cannot change the nursery of an order that already has items';
    END IF;
END$$

CREATE TRIGGER trg_restock_after_insert
AFTER INSERT ON Restock
FOR EACH ROW
BEGIN
    UPDATE Nursery_Stock
    SET stock_qty = stock_qty + NEW.quantity
    WHERE nursery_id = NEW.nursery_id AND plant_id = NEW.plant_id;
END$$

CREATE TRIGGER trg_restock_before_update
BEFORE UPDATE ON Restock
FOR EACH ROW
BEGIN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Restock records cannot be modified';
END$$

CREATE TRIGGER trg_restock_before_delete
BEFORE DELETE ON Restock
FOR EACH ROW
BEGIN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Restock records cannot be deleted';
END$$

DELIMITER ;

