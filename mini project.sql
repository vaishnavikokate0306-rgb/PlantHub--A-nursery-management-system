CREATE VIEW v_customer_details AS
SELECT customer_id, name, contact_no, address, date_of_birth
FROM Customer;

CREATE VIEW v_staff_details AS
SELECT s.staff_id, s.name, s.position, s.experience_years,
       n.name AS nursery
FROM Staff s JOIN Nursery n ON n.nursery_id = s.nursery_id;

CREATE VIEW v_stock_details AS
SELECT n.name AS nursery, p.plant_id, p.name AS plant, p.gender, pt.type_name AS category,
       ns.stock_qty, ns.unit_price, ns.reorder_level
FROM Nursery_Stock ns
JOIN Nursery    n  ON n.nursery_id = ns.nursery_id
JOIN Plant      p  ON p.plant_id   = ns.plant_id
JOIN Plant_Type pt ON pt.type_id   = p.type_id;

CREATE VIEW v_low_stock AS
SELECT nursery, plant_id, plant, gender, category, stock_qty, reorder_level
FROM v_stock_details
WHERE stock_qty < reorder_level;

CREATE VIEW v_order_summary AS
SELECT o.order_id, o.order_date, c.name AS customer, n.name AS nursery, o.payment_mode,
       COUNT(oi.plant_id)  AS distinct_plants,
       SUM(oi.quantity)    AS total_quantity,
       SUM((oi.quantity * oi.unit_price))  AS order_total
FROM Orders o
JOIN Customer    c  ON c.customer_id = o.customer_id
JOIN Nursery     n  ON n.nursery_id  = o.nursery_id
LEFT JOIN Order_Items oi ON oi.order_id = o.order_id
GROUP BY o.order_id, o.order_date, c.name, n.name, o.payment_mode;

